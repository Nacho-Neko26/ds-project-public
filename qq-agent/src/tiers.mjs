/** 这一档的语气设定；未知档位返回空串（agent.mjs 那边回落到旧的一句短描述） */
export function tierVoice(tierKey, { isGroup = false } = {}) {
  const v = VOICE[tierKey];
  if (!v) return '';
  const head = '【交情怎么影响语气】上面这段是底色；这一轮真在生气、难过、犯困，就按情绪来——该短就短、该冷就冷，别硬演热络。';
  if (isGroup) {
    return `${head}\n${v}\n（这是群聊：亲近的话、贴人的动作、吃醋的酸味都收着，群里只留说话的语气和分寸。）`;
  }
  return `${head}\n${v}`;
}

/** 有哪些档位配了语气（给测试和外部查） */
export function knownTiers() {
  return Object.keys(VOICE);
}
